import React, { useEffect, useState } from 'react';
import { View, ScrollView } from 'react-native';
import { Stack, useRouter } from 'expo-router';
import { SafeAreaView } from 'react-native-safe-area-context';

import { ScreenBackground } from '@/components/ui/ScreenBackground';
import { useTheme } from '@/theme';
import { usePredictionStore } from '@/store/prediction-store';
import { UserScanSummaryCard } from '@/features/chat/components/user-scan-summary-card';
import { ResultActions } from '../components/result-actions';
import { ThemeText } from '@/components/ui/theme/ThemeText';

export function ResultScreen() {
  const { theme, isDark } = useTheme();
  const router = useRouter();
  
  // Take a snapshot on mount so clearing the store doesn't break the UI or trigger redirects.
  const [localPrediction] = useState(() => usePredictionStore.getState().pending);

  // If we somehow get here without a prediction originally, go back
  useEffect(() => {
    if (!localPrediction) {
      router.push('/scan-upload' as never);
    }
  }, [localPrediction, router]);

  if (!localPrediction) {
    return (
      <View style={{ flex: 1, backgroundColor: theme.colors.background.base }}>
        <ScreenBackground />
      </View>
    );
  }

  return (
    <View style={{ flex: 1, backgroundColor: theme.colors.background.base }}>
      <ScreenBackground />
      <Stack.Screen
        options={{
          headerShown: true,
          headerStyle: {
            backgroundColor: isDark ? theme.colors.background.base : '#fff',
          },
          headerTitle: () => <ThemeText style={{ color: isDark ? '#E8F1FF' : '#111827' }} className="text-xl font-bold mb-2">Scan Result</ThemeText>,
          headerTintColor: isDark ? '#E8F1FF' : '#111827',
          headerShadowVisible: false,
          headerLeft: () => null, // Prevent going back via header
          gestureEnabled: false,
        }}
      />
      
      <SafeAreaView style={{ flex: 1 }} edges={['bottom', 'left', 'right']}>
        <ScrollView
          className="flex-1"
          contentContainerStyle={{ padding: 20, paddingBottom: 40 }}
          showsVerticalScrollIndicator={false}
        >
          <View className="mb-4">
            <UserScanSummaryCard
              prediction={localPrediction.prediction}
              confidence={localPrediction.confidence}
            />
          </View>

          <ResultActions prediction={localPrediction} />

          <View className="mt-8 p-4 rounded-xl bg-amber-500/10 border border-amber-500/20" accessibilityLabel="medical disclaimer">
            <ThemeText className="text-xs text-amber-500 text-center leading-relaxed">
              This screening result is generated by an AI system and is not a medical diagnosis. Please consult a qualified ophthalmologist for professional evaluation and treatment decisions.
            </ThemeText>
          </View>
        </ScrollView>
      </SafeAreaView>
    </View>
  );
}
