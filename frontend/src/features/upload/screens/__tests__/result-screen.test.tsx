import React from 'react';
import { render, fireEvent, act, waitFor } from '@testing-library/react-native';
import { ResultScreen } from '../result-screen';
import { usePredictionStore } from '@/store/prediction-store';
import { useChatStore } from '@/features/chat/store/chat-store';
import { useUploadWorkflowStore } from '@/features/upload/store/upload-workflow-store';
import { ANALYSIS_FAILED_MESSAGE } from '@/shared/uploads/upload-errors';

const mockPush = jest.fn();
const mockReplace = jest.fn();
jest.mock('expo-router', () => ({
  useRouter: () => ({
    push: mockPush,
    replace: mockReplace,
  }),
  Stack: {
    Screen: () => null,
  },
}));

jest.mock('@/theme', () => ({
  useTheme: () => ({
    theme: {
      colors: {
        background: { base: '#fff', surface: '#fff', elevated: '#fff', surfaceStrong: '#fff' },
        border: { soft: '#ccc', subtle: '#ddd' },
        text: { primary: '#000', secondary: '#555', success: '#22c55e', warning: '#eab308', danger: '#ef4444' },
        accent: { primary: '#244A85' },
        chatUserBubbleText: '#000',
        floatingOrbPrimary: '#000',
        floatingOrbSecondary: '#000',
        floatingOrbOpacityScale: { primary: 1, secondary: 1 },
        successSurface: '#f0fdf4',
        errorSurface: '#fef2f2',
        accentSurface: '#eff6ff',
      },
      spacing: {
        xs: 4,
        sm: 8,
        md: 12,
        lg: 16,
        xl: 20,
        xxl: 24,
      },
      radii: {
        md: 8,
        lg: 12,
        xl: 16,
        full: 9999,
      },
    },
    isDark: false,
  }),
}));

describe('ResultScreen Component', () => {
  beforeEach(() => {
    jest.clearAllMocks();
    usePredictionStore.getState().clearAll();
    useChatStore.getState().clearActiveChat();
    useUploadWorkflowStore.getState().clearWorkflow();
  });

  it('redirects to /scan-upload if the screen is reached without a pending scan result', async () => {
    await render(<ResultScreen />);

    await waitFor(() => {
      expect(mockReplace).toHaveBeenCalledWith('/scan-upload');
    });
  });

  it('renders the successful home-scan result and exposes the current action buttons', async () => {
    usePredictionStore.getState().setPending({
      prediction: 'Immature_Cataract',
      confidence: 0.87,
      uploadedImageUrl: 'https://s3/pic.jpg',
      chatId: 'chat-123',
    });

    const { getByText, queryByText } = await render(<ResultScreen />);

    expect(getByText('Immature Cataract')).toBeTruthy();
    expect(getByText('AI Analysis this scan with approximately 87% confidence.')).toBeTruthy();
    expect(
      getByText(
        'This screening result is generated by an AI system and is not a medical diagnosis. Please consult a qualified ophthalmologist for professional evaluation and treatment decisions.'
      )
    ).toBeTruthy();
    expect(getByText('Discuss With SpandaVidya AI')).toBeTruthy();
    expect(getByText('Start New Scan')).toBeTruthy();
    expect(getByText('Return to Dashboard')).toBeTruthy();
    expect(queryByText('Retake Scan')).toBeNull();
    expect(queryByText('Return Home')).toBeNull();
  });

  it('sets the active chat from prediction.chatId and enables auto consultation when Discuss is pressed', async () => {
    usePredictionStore.getState().setPending({
      prediction: 'Normal',
      confidence: 0.99,
      uploadedImageUrl: 'https://s3/pic.jpg',
      chatId: 'chat-123',
    });

    const { getByText } = await render(<ResultScreen />);
    const discussButton = getByText('Discuss With SpandaVidya AI');

    await act(async () => {
      fireEvent.press(discussButton);
    });

    expect(useChatStore.getState().activeChatId).toBe('chat-123');
    expect(usePredictionStore.getState().shouldAutoConsult).toBe(true);
    expect(mockPush).toHaveBeenCalledWith('/(tabs)/chat');
  });

  it('renders the error state with recovery actions and routes correctly from each button', async () => {
    useUploadWorkflowStore.getState().setLastErrorCode('ANALYSIS_FAILED');

    const firstRender = await render(<ResultScreen />);
    const { getByText } = firstRender;

    expect(getByText('Analysis Could Not Be Completed')).toBeTruthy();
    expect(getByText(ANALYSIS_FAILED_MESSAGE)).toBeTruthy();
    expect(getByText('Retake Scan')).toBeTruthy();
    expect(getByText('Return Home')).toBeTruthy();

    await act(async () => {
      fireEvent.press(getByText('Retake Scan'));
    });

    expect(usePredictionStore.getState().pending).toBeNull();
    expect(useUploadWorkflowStore.getState().lastErrorCode).toBeNull();
    expect(mockReplace).toHaveBeenCalledWith('/scan-upload');

    firstRender.unmount();

    usePredictionStore.getState().setPending({
      prediction: 'Normal',
      confidence: 0.99,
      uploadedImageUrl: 'https://s3/pic.jpg',
      chatId: 'chat-123',
    });
    useUploadWorkflowStore.getState().setLastErrorCode('ANALYSIS_FAILED');
    mockReplace.mockClear();

    const secondRender = await render(<ResultScreen />);

    await act(async () => {
      fireEvent.press(secondRender.getByText('Return Home'));
    });

    expect(usePredictionStore.getState().pending).toBeNull();
    expect(useUploadWorkflowStore.getState().lastErrorCode).toBeNull();
    expect(mockReplace).toHaveBeenCalledWith('/(tabs)');
  });

});
