import React from 'react';
import { render, fireEvent } from '@testing-library/react-native';
import { ResultScreen } from '../result-screen';
import { usePredictionStore } from '@/store/prediction-store';
import { useRouter } from 'expo-router';

const mockPush = jest.fn();
const mockReplace = jest.fn();
jest.mock('expo-router', () => ({
  useRouter: () => ({
    push: mockPush,
    replace: mockReplace,
  }),
  Stack: {
    Screen: () => null,
  },
}));

jest.mock('@/theme', () => ({
  useTheme: () => ({
    theme: {
      colors: {
        background: { base: '#fff' },
        border: { soft: '#ccc', subtle: '#ddd' },
        text: { primary: '#000', secondary: '#555' },
        accent: { primary: '#244A85' },
        chatUserBubbleText: '#000',
        floatingOrbPrimary: '#000',
        floatingOrbSecondary: '#000',
      },
    },
    isDark: false,
  }),
}));

describe('ResultScreen Component', () => {
  let originalAlert: any;
  const mockAlert = jest.fn();

  beforeAll(() => {
    originalAlert = global.alert;
    global.alert = mockAlert;
  });

  afterAll(() => {
    global.alert = originalAlert;
  });

  beforeEach(() => {
    jest.clearAllMocks();
    usePredictionStore.getState().clearAll();
  });

  it('redirects to /scan-upload if no pending prediction is in store', () => {
    render(<ResultScreen />);
    expect(mockPush).toHaveBeenCalledWith('/scan-upload');
  });

  it('renders prediction, confidence, medical disclaimer, and action buttons', () => {
    usePredictionStore.getState().setPending({
      prediction: 'Immature_Cataract',
      confidence: 0.87,
      uploadedImageUrl: 'https://s3/pic.jpg',
      chatId: 'chat-123',
    });

    const { getByText, getByLabelText } = render(<ResultScreen />);

    // Prediction and confidence labels
    expect(getByText('Immature Cataract')).toBeTruthy();
    expect(getByText('AI detected this scan with approximately 87% confidence.')).toBeTruthy();

    // Medical disclaimer renders
    expect(
      getByText(
        'This screening result is generated by an AI system and is not a medical diagnosis. Please consult a qualified ophthalmologist for professional evaluation and treatment decisions.'
      )
    ).toBeTruthy();

    // Renders action buttons
    expect(getByText('Discuss With SpandaVidya AI')).toBeTruthy();
    expect(getByText('Start New Scan')).toBeTruthy();
    expect(getByText('Return to Dashboard')).toBeTruthy();
  });

  it('navigates to chat tab if discuss button is pressed and chatId exists', () => {
    usePredictionStore.getState().setPending({
      prediction: 'Normal',
      confidence: 0.99,
      uploadedImageUrl: 'https://s3/pic.jpg',
      chatId: 'chat-123',
    });

    const { getByText } = render(<ResultScreen />);
    const discussButton = getByText('Discuss With SpandaVidya AI');

    fireEvent.press(discussButton);
    expect(mockPush).toHaveBeenCalledWith('/(tabs)/chat');
  });

  it('shows alert warning if discuss button is pressed and chatId is missing', () => {
    usePredictionStore.getState().setPending({
      prediction: 'Normal',
      confidence: 0.99,
      uploadedImageUrl: 'https://s3/pic.jpg',
      chatId: '', // missing
    });

    const { getByText } = render(<ResultScreen />);
    const discussButton = getByText('Discuss With SpandaVidya AI');

    fireEvent.press(discussButton);
    expect(mockAlert).toHaveBeenCalledWith('Chat session not found. Please try scanning again.');
    expect(mockPush).not.toHaveBeenCalled();
  });
});
